"""Состояния создания мема (FSM).

Зачем FSM. Пользователь вводит данные по шагам обычными сообщениями (фото, текст), и без
состояния бот не отличил бы «верхний текст» от «нижнего» или от случайного сообщения.
Состояние говорит боту, чего он ждёт именно сейчас.

    choosing_template ─(шаблон)────────────► waiting_top ─(текст)─► waiting_bottom ─(текст)─► preview
            │                                    ▲                                              │
            └─(«Своё фото»)─► waiting_photo ─(фото)┘            «Заново» ◄────────────────────────┤
                                                                публикация/сохранение/отмена ──► (конец)
"""

from aiogram.fsm.state import State, StatesGroup


class MemeStates(StatesGroup):
    choosing_template = State()  # выбор шаблона или «своё фото»
    waiting_photo = State()  # ждём фото от пользователя
    waiting_top = State()  # ждём верхний текст
    waiting_bottom = State()  # ждём нижний текст
    preview = State()  # готовый мем показан, ждём решения
