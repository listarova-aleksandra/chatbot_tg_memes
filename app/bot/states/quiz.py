"""Состояния викторины (FSM: конечный автомат).

Зачем FSM именно здесь. Игра это многошаговый процесс, и бот должен помнить, на каком
шаге находится каждый игрок. Telegram каждый апдейт доставляет независимо, поэтому
«текущий шаг» хранится в состоянии пользователя, а данные игры (какие вопросы, на каком
мы сейчас) лежат в `state.data`. Состояние ещё и защищает: кнопка принимается только на
том шаге, где она имеет смысл (например, ответ нельзя засчитать дважды).

    choosing_category ─(выбрал категорию)─► answering ─(нажал вариант)─► reviewing
                                                ▲                            │
                                                └────── «Дальше» ◄───────────┤
                                                                             │ (вопросы кончились)
                                                              finished ◄─────┘
    finished ─(«Играть ещё»)─► choosing_category
"""

from aiogram.fsm.state import State, StatesGroup


class QuizStates(StatesGroup):
    choosing_category = State()  # на экране выбор категории
    answering = State()  # показан вопрос, ждём ответ
    reviewing = State()  # ответ принят, показано объяснение, ждём «Дальше»
    finished = State()  # игра окончена, показан итог
