"""Ошибки внешних API.

Одна иерархия для всех сервисов: HTTP-клиент превращает любые сбои (таймаут, 500, 429,
мусор вместо JSON) в понятные исключения, а сервисы ловят `ApiError` и отдают
вызывающему коду безопасный результат. До Telegram-хендлеров исключения не доходят.
"""


class ApiError(Exception):
    """Базовая ошибка обращения к внешнему API."""


class ApiUnavailableError(ApiError):
    """Сервис не отвечает: таймаут, обрыв соединения или HTTP 5xx (после всех повторов)."""


class ApiRateLimitedError(ApiError):
    """HTTP 429: превышен лимит запросов (после всех повторов)."""


class ApiAuthError(ApiError):
    """HTTP 401/403: неверный или отсутствующий ключ. Повторять бессмысленно."""


class ApiClientError(ApiError):
    """Прочие HTTP 4xx (например, 404): запрос неверный, повторять бессмысленно."""


class ApiBadResponseError(ApiError):
    """Ответ получен, но это не тот JSON, который ожидали (или он пустой)."""
